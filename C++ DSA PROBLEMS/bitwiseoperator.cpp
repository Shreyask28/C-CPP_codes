#include <iostream>
using namespace std;
int main(){
    cout<< (6 & 10) << endl;  // Bitwise AND
    cout<< (5 | 3) << endl;  // Bitwise OR
    cout<< (5 ^ 3) << endl;  // Bitwise XOR
    cout<< (~5) << endl;     // Bitwise NOT
    cout<< (5 << 1) << endl; // Left Shift
    cout<< (5 >> 1) << endl; // Right Shift
    return 0;   


}